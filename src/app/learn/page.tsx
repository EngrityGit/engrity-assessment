import Link from "next/link";
import { redirect } from "next/navigation";
import { auth } from "@/lib/auth";
import { prisma } from "@/lib/prisma";
import AppShell from "@/components/ui/AppShell";
import { MODULES, modulesForRole } from "@/lib/learning";
import { computeXp } from "@/lib/learning/xp";

export const metadata = { title: "Learn" };

export default async function LearnPage() {
  const session = await auth();
  if (!session) redirect("/login");
  const cid = session.user.candidateId;
  const candidate = cid ? await prisma.candidate.findUnique({ where: { id: cid } }) : null;
  const progress = cid ? await prisma.lessonProgress.findMany({ where: { candidateId: cid } }) : [];
  const games = cid
    ? await prisma.gameScore.groupBy({ by: ["game"], where: { candidateId: cid }, _max: { score: true } })
    : [];
  const done = new Set(progress.filter((p) => p.completedAt).map((p) => p.lessonSlug));
  const xp = computeXp(progress, games.map((g) => g._max.score ?? 0));
  const modules = modulesForRole(candidate?.targetRole);
  const total = MODULES.reduce((a, m) => a + m.lessons.length, 0);

  return (
    <AppShell>
      <div className="mb-6 flex flex-wrap items-end justify-between gap-4">
        <div>
          <h1 className="text-2xl font-extrabold tracking-tight">Learning hub</h1>
          <p className="text-sm text-ink/70">Short lessons, quick checks and mini-games to sharpen the skills your role needs.</p>
        </div>
        <div className="card min-w-[14rem] p-4">
          <div className="flex items-baseline justify-between">
            <p className="text-xs font-bold text-ink/60">Level {xp.level}</p>
            <p className="text-xs font-bold text-brand">{xp.xp} XP</p>
          </div>
          <div className="mt-2 h-2.5 overflow-hidden rounded-full bg-accent">
            <div className="anim-bar h-full rounded-full bg-brand" style={{ width: `${(xp.intoLevel / xp.perLevel) * 100}%` }} />
          </div>
          <p className="mt-1 text-[11px] text-ink/60">{done.size}/{total} lessons complete</p>
        </div>
      </div>

      <div className="mb-8 grid gap-4 sm:grid-cols-2 stagger">
        <Link href="/learn/practice" className="card-accent card-hover block p-6">
          <p className="text-2xl">🤖</p>
          <h2 className="mt-1 font-extrabold">AI practice questions</h2>
          <p className="text-sm text-ink/70">Unlimited fresh questions on any topic, with explanations — generated by Claude or OpenAI.</p>
        </Link>
        <Link href="/learn/games" className="card-accent card-hover block p-6">
          <p className="text-2xl">🎮</p>
          <h2 className="mt-1 font-extrabold">Mini-games</h2>
          <p className="text-sm text-ink/70">Symbol Match, Speed Round and Error Hunt — learn by playing, earn XP.</p>
        </Link>
      </div>

      <div className="grid gap-5 lg:grid-cols-2 stagger">
        {modules.map((m) => {
          const completed = m.lessons.filter((l) => done.has(l.slug)).length;
          const recommended = candidate?.targetRole && m.roles.includes(candidate.targetRole);
          return (
            <section key={m.slug} className="card p-6">
              <div className="flex items-start justify-between gap-3">
                <div>
                  <p className="text-3xl">{m.icon}</p>
                  <h2 className="mt-1 text-lg font-extrabold">{m.title}</h2>
                  <p className="text-sm text-ink/70">{m.blurb}</p>
                </div>
                {recommended && <span className="badge badge-blue shrink-0">For your role</span>}
              </div>
              <div className="mt-4 h-2 overflow-hidden rounded-full bg-surface">
                <div className="anim-bar h-full rounded-full bg-brand" style={{ width: `${(completed / m.lessons.length) * 100}%` }} />
              </div>
              <ul className="mt-4 space-y-2">
                {m.lessons.map((l) => (
                  <li key={l.slug}>
                    <Link href={`/learn/${m.slug}/${l.slug}`} className="flex items-center gap-3 rounded-[15px] bg-surface px-3 py-2.5 text-sm transition hover:bg-accent">
                      <span className={`flex h-6 w-6 shrink-0 items-center justify-center rounded-full text-xs font-bold ${done.has(l.slug) ? "bg-green-500 text-white" : "bg-white text-ink/50"}`}>
                        {done.has(l.slug) ? "✓" : "•"}
                      </span>
                      <span className="flex-1 font-semibold">{l.title}</span>
                      <span className="text-xs text-ink/50">{l.minutes} min</span>
                    </Link>
                  </li>
                ))}
              </ul>
            </section>
          );
        })}
      </div>
    </AppShell>
  );
}
